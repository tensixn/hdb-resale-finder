-- Initial schema for the HDB Resale Flat Search and Analysis System.
-- Written in the SQL subset shared by PostgreSQL and H2 (PostgreSQL mode).

CREATE TABLE app_user (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email            VARCHAR(254) NOT NULL UNIQUE,
    password_hash    VARCHAR(100) NOT NULL,
    role             VARCHAR(20)  NOT NULL DEFAULT 'HOME_BUYER',
    failed_attempts  INT          NOT NULL DEFAULT 0,
    locked_until     TIMESTAMP,
    consent_at       TIMESTAMP    NOT NULL,
    created_at       TIMESTAMP    NOT NULL
);

CREATE TABLE user_session (
    id            VARCHAR(36) PRIMARY KEY,
    user_id       BIGINT      NOT NULL REFERENCES app_user (id) ON DELETE CASCADE,
    created_at    TIMESTAMP   NOT NULL,
    last_seen_at  TIMESTAMP   NOT NULL,
    expires_at    TIMESTAMP   NOT NULL,
    revoked       BOOLEAN     NOT NULL DEFAULT FALSE
);
CREATE INDEX idx_session_user ON user_session (user_id);

-- Income and parental address are stored AES-256-GCM encrypted (NFR-6).
CREATE TABLE financial_profile (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id             BIGINT       NOT NULL UNIQUE REFERENCES app_user (id) ON DELETE CASCADE,
    household_income    VARCHAR(512) NOT NULL,
    marital_status      VARCHAR(20)  NOT NULL,
    parent_postal_code  VARCHAR(512),
    living_with_parents BOOLEAN      NOT NULL DEFAULT FALSE,
    updated_at          TIMESTAMP    NOT NULL
);

CREATE TABLE weight_profile (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id             BIGINT NOT NULL UNIQUE REFERENCES app_user (id) ON DELETE CASCADE,
    lease_weight        DOUBLE PRECISION NOT NULL,
    safety_weight       DOUBLE PRECISION NOT NULL,
    density_weight      DOUBLE PRECISION NOT NULL,
    air_quality_weight  DOUBLE PRECISION NOT NULL,
    updated_at          TIMESTAMP NOT NULL
);

CREATE TABLE town (
    name       VARCHAR(40) PRIMARY KEY,
    latitude   DOUBLE PRECISION NOT NULL,
    longitude  DOUBLE PRECISION NOT NULL,
    region     VARCHAR(10) NOT NULL
);

CREATE TABLE crime_record (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    town               VARCHAR(40) NOT NULL UNIQUE,
    rate_per_thousand  DOUBLE PRECISION NOT NULL,
    record_year        INT NOT NULL
);

CREATE TABLE density_record (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    town                VARCHAR(40) NOT NULL UNIQUE,
    residents_per_ha    DOUBLE PRECISION NOT NULL,
    record_year         INT NOT NULL
);

CREATE TABLE air_quality_reading (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    region       VARCHAR(10) NOT NULL,
    psi          INT NOT NULL,
    recorded_at  TIMESTAMP NOT NULL
);
CREATE INDEX idx_psi_region_time ON air_quality_reading (region, recorded_at);

CREATE TABLE flat (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    block                VARCHAR(10) NOT NULL,
    street               VARCHAR(80) NOT NULL,
    town                 VARCHAR(40) NOT NULL,
    flat_type            VARCHAR(20) NOT NULL,
    floor_area_sqm       DOUBLE PRECISION NOT NULL,
    storey_range         VARCHAR(20) NOT NULL,
    lease_commence_year  INT NOT NULL,
    latitude             DOUBLE PRECISION NOT NULL,
    longitude            DOUBLE PRECISION NOT NULL,
    region               VARCHAR(10) NOT NULL,
    latest_price         BIGINT,
    latest_month         VARCHAR(7),
    CONSTRAINT uq_flat UNIQUE (block, street, flat_type, storey_range)
);
-- NFR-1: indexes on town, flat type and price.
CREATE INDEX idx_flat_town ON flat (town);
CREATE INDEX idx_flat_type ON flat (flat_type);
CREATE INDEX idx_flat_price ON flat (latest_price);

CREATE TABLE resale_transaction (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    flat_id         BIGINT NOT NULL REFERENCES flat (id) ON DELETE CASCADE,
    txn_month       VARCHAR(7) NOT NULL,
    resale_price    BIGINT NOT NULL,
    source          VARCHAR(20) NOT NULL DEFAULT 'SEED',
    CONSTRAINT uq_tx UNIQUE (flat_id, txn_month, resale_price)
);
CREATE INDEX idx_tx_month ON resale_transaction (txn_month);

CREATE TABLE valuation_baseline (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    town              VARCHAR(40) NOT NULL,
    flat_type         VARCHAR(20) NOT NULL,
    average_price     BIGINT NOT NULL,
    average_psm       DOUBLE PRECISION NOT NULL,
    sample_size       INT NOT NULL,
    window_start      VARCHAR(7) NOT NULL,
    window_end        VARCHAR(7) NOT NULL,
    computed_at       TIMESTAMP NOT NULL,
    CONSTRAINT uq_baseline UNIQUE (town, flat_type)
);

CREATE TABLE valuation_batch_job (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    started_at        TIMESTAMP NOT NULL,
    finished_at       TIMESTAMP,
    status            VARCHAR(20) NOT NULL,
    records_ingested  INT NOT NULL DEFAULT 0,
    trigger_reason    VARCHAR(20) NOT NULL,
    message           VARCHAR(500)
);

CREATE TABLE school (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR(120) NOT NULL,
    town       VARCHAR(40) NOT NULL,
    latitude   DOUBLE PRECISION NOT NULL,
    longitude  DOUBLE PRECISION NOT NULL
);

CREATE TABLE bookmark (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT NOT NULL REFERENCES app_user (id) ON DELETE CASCADE,
    flat_id     BIGINT NOT NULL REFERENCES flat (id) ON DELETE CASCADE,
    created_at  TIMESTAMP NOT NULL,
    CONSTRAINT uq_bookmark UNIQUE (user_id, flat_id)
);

CREATE TABLE search_criteria (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id           BIGINT NOT NULL REFERENCES app_user (id) ON DELETE CASCADE,
    workplace1        VARCHAR(200) NOT NULL,
    workplace2        VARCHAR(200),
    transport_modes   VARCHAR(60) NOT NULL,
    min_price         BIGINT,
    max_price         BIGINT,
    flat_types        VARCHAR(200),
    towns             VARCHAR(1000),
    created_at        TIMESTAMP NOT NULL
);
